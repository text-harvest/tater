"""Regenerate tater/ui/assets/icons.js: the Tabler icons tater uses, served by tater itself.

dash-iconify fetches each icon's SVG from api.iconify.design (or its mirrors) unless the page
has already registered it through ``window.IconifyPreload``. That file does the registering,
so pages show their icons without reaching the internet.

Run it after adding an icon (``tests/test_icons.py`` fails until you do):

    curl -sSLO https://registry.npmjs.org/@iconify-json/tabler/-/tabler-<version>.tgz
    tar -xzf tabler-<version>.tgz
    python scripts/build_icons.py package/

It scans ``tater/`` for the icon names in use and copies those icons' bodies from the
package's ``icons.json``. Tater uses only the Tabler set; use a Tabler icon rather than
adding another set.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TATER = ROOT / "tater"
OUT = TATER / "ui" / "assets" / "icons.js"
PREFIX = "tabler"

# Icon-set prefixes worth recognising, so an icon from another set is reported rather than missed.
KNOWN_PREFIXES = {"tabler", "fa", "fa-regular", "fa-solid", "fa-brands", "fa6-regular", "fa6-solid",
                  "mdi", "carbon", "ic", "ph", "lucide", "bi", "material-symbols", "heroicons", "ri"}
_QUOTED = re.compile(r"""["']([a-z][a-z0-9-]*):([a-z0-9][a-z0-9-]*)["']""")
_ICON_ARG = re.compile(r"""\bicon["']?\s*[=:]\s*["']([^"']+)["']""")


def icons_used(root: Path = TATER) -> set[str]:
    """Every ``prefix:name`` icon in tater's Python, JavaScript and example files."""
    found = set()
    for path in root.rglob("*"):
        if path.suffix not in (".py", ".js", ".json") or path == OUT:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for prefix, name in _QUOTED.findall(text):
            if prefix in KNOWN_PREFIXES:
                found.add(f"{prefix}:{name}")
        for value in _ICON_ARG.findall(text):
            if ":" in value:
                found.add(value)
    return found


def read_preload(path: Path = OUT) -> list[dict]:
    """The ``window.IconifyPreload`` value in icons.js."""
    match = re.search(r"^window\.IconifyPreload = (.*);$", path.read_text(encoding="utf-8"), re.M)
    if not match:
        raise ValueError(f"no IconifyPreload in {path}")
    return json.loads(match.group(1))


def build(package_dir: Path) -> str:
    data = json.loads((package_dir / "icons.json").read_text(encoding="utf-8"))
    info = json.loads((package_dir / "info.json").read_text(encoding="utf-8"))
    version = json.loads((package_dir / "package.json").read_text(encoding="utf-8"))["version"]
    used = sorted(icons_used())
    others = [i for i in used if not i.startswith(PREFIX + ":")]
    if others:
        raise SystemExit(f"not Tabler icons: {', '.join(others)}. Use a Tabler icon instead.")
    icons = {}
    for full in used:
        name = full.split(":", 1)[1]
        source, alias = name, data.get("aliases", {}).get(name)
        if alias:
            if set(alias) - {"parent"}:
                raise SystemExit(f"{full} is a transformed alias; pick the icon it's based on")
            source = alias["parent"]
        if source not in data["icons"]:
            raise SystemExit(f"{full} is not in @iconify-json/tabler {version}")
        icons[name] = data["icons"][source]
    preload = [{"prefix": PREFIX, "width": data.get("width", 24), "height": data.get("height", 24), "icons": icons}]
    header = (
        f"/* Generated by scripts/build_icons.py from @iconify-json/tabler {version} "
        f"({info['name']} {info.get('version', '')}). Don't edit; re-run the script.\n"
        f" * {info['name']}: {info['license']['spdx']} licence, (c) {info['author']['name']}, "
        f"{info['author']['url']}\n"
        " * Registers the icons tater uses, so dash-iconify doesn't fetch them from api.iconify.design. */\n"
    )
    return header + "window.IconifyPreload = " + json.dumps(preload, ensure_ascii=False, separators=(",", ":")) + ";\n"


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__)
        return 2
    OUT.write_text(build(Path(argv[0])), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(read_preload()[0]['icons'])} icons)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
